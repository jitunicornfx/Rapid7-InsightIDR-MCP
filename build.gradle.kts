// ---------------------------------------------------------------------------
// Build-time server identity
//
// `version` above is the single source of truth. This task bakes it — plus the git commit the build
// came from — into a resource that BuildInfo.kt reads at runtime, so the version reported by
// insightidr_server_info, the MCP Implementation block, the update comparison, the outbound
// User-Agent and the spool manifest can never drift from the build that produced them.
// ---------------------------------------------------------------------------

/**
 * Runs a git command and returns its trimmed stdout, or "" for ANY failure: git not installed, not a
 * git checkout, a non-zero exit, or a process that hangs. A missing SHA must never fail the build.
 *
 * A ValueSource rather than a configuration-time exec, so this stays correct if the configuration
 * cache is ever enabled.
 */
abstract class GitOutput : ValueSource<String, GitOutput.Params> {
    interface Params : ValueSourceParameters {
        val projectDir: DirectoryProperty
        val args: ListProperty<String>
    }

    override fun obtain(): String = runCatching {
        val process = ProcessBuilder(listOf("git") + parameters.args.get())
            .directory(parameters.projectDir.get().asFile)
            .redirectError(ProcessBuilder.Redirect.DISCARD)
            .start()
        val stdout = process.inputStream.bufferedReader().readText()
        if (!process.waitFor(10, TimeUnit.SECONDS)) {
            process.destroyForcibly()
            ""
        } else if (process.exitValue() == 0) {
            stdout.trim()
        } else {
            ""
        }
    }.getOrDefault("")
}

fun gitOutput(vararg args: String): Provider<String> =
    providers.of(GitOutput::class.java) {
        parameters.projectDir.set(layout.projectDirectory)
        parameters.args.set(args.toList())
    }

// Deliberately not `git describe`: it needs tags and fails on a shallow CI clone.
val gitSha: Provider<String> = gitOutput("rev-parse", "--short=12", "HEAD")
val gitCommitTime: Provider<String> = gitOutput("log", "-1", "--format=%cI")
val gitStatus: Provider<String> = gitOutput("status", "--porcelain", "--untracked-files=no")

// An empty status also means "no git at all", so only claim dirtiness when there IS a SHA.
val gitDirty: Provider<Boolean> = provider { gitSha.get().isNotEmpty() && gitStatus.get().isNotBlank() }

val generateBuildInfo = tasks.register("generateBuildInfo") {
    group = "build"
    description = "Writes the build-time server identity resource read by BuildInfo.kt."

    val projectVersion = project.version.toString()
    val outputDir = layout.buildDirectory.dir("generated/resources/buildinfo")

    // These four are the ONLY declared inputs, and every one of them is stable across an ordinary
    // rebuild. The generation timestamp written below is deliberately NOT an input: a wall clock as
    // an input would leave this task — and therefore processResources, jar, shadowJar and test —
    // out of date on every single build, turning every build into a full build.
    inputs.property("version", projectVersion)
    inputs.property("gitSha", gitSha)
    inputs.property("gitCommitTime", gitCommitTime)
    inputs.property("gitDirty", gitDirty)
    outputs.dir(outputDir)

    // Capture providers, never `project`, so the action stays configuration-cache safe.
    val sha = gitSha
    val commitTime = gitCommitTime
    val dirty = gitDirty

    doLast {
        val target = outputDir.get().asFile.resolve("META-INF").apply { mkdirs() }
            .resolve("insightidr-mcp-build.properties")
        // Hand-written rather than Properties.store(), which prepends a "#<date>" comment and would
        // put a wall clock into the bytes unconditionally. Every value is drawn from [0-9A-Za-z.:+-]
        // only, so no .properties escaping is needed; BuildInfo re-validates on the way in anyway.
        target.writeText(
            buildString {
                appendLine("# Generated by :generateBuildInfo - do not edit.")
                appendLine("version=$projectVersion")
                sha.get().takeIf { it.isNotEmpty() }?.let { appendLine("git.sha=$it") }
                commitTime.get().takeIf { it.isNotEmpty() }?.let { appendLine("git.commitTime=$it") }
                appendLine("git.dirty=${dirty.get()}")
                appendLine("build.generatedAt=" + Instant.now().truncatedTo(ChronoUnit.SECONDS))
            },
            Charsets.UTF_8,
        )
    }
}

sourceSets.named("main") {
    // Passing the TaskProvider (not a bare path) carries the task dependency, so processResources,
    // jar, shadowJar, `run` and `test` all see the resource without an explicit dependsOn.
    resources.srcDir(generateBuildInfo)
}

